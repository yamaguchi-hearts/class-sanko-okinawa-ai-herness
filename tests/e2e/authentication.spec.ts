import { test, expect, _electron as electron } from '@playwright/test'
import { mkdtemp, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

test.setTimeout(300_000)
test('first setup, restart login, STAFF code setup and Main authorization', async () => {
  const userData = await mkdtemp(join(tmpdir(), 'inventory-auth-e2e-'))
  const env: Record<string, string> = {}
  for (const [key, value] of Object.entries(process.env)) if (value !== undefined) env[key] = value
  delete env.ELECTRON_RUN_AS_NODE
  let app = await electron.launch({ args: ['.', `--user-data-dir=${userData}`], env })
  try {
    let window = await app.firstWindow()
    await window.getByLabel('店舗名').fill('E2E店舗')
    await window.getByLabel('管理者表示名').fill('管理責任者')
    await window.getByLabel('ログインID').fill('admin')
    await window.getByLabel('パスワード（4〜128文字）').fill('abcd')
    await window.getByLabel('パスワード（確認）').fill('abce')
    await window.getByRole('button', { name: '初期設定を完了' }).click()
    await expect(window.getByRole('alert')).toContainText('入力内容を確認してください')
    await window.getByLabel('パスワード（4〜128文字）').fill('abcd')
    await window.getByLabel('パスワード（確認）').fill('abcd')
    await window.getByRole('button', { name: '初期設定を完了' }).click()
    await expect(window.getByRole('heading', { name: 'ダッシュボード' })).toBeVisible()
    await window.getByRole('button', { name: '商品一覧' }).click()
    await app.close()

    app = await electron.launch({ args: ['.', `--user-data-dir=${userData}`], env })
    window = await app.firstWindow()
    await expect(window.getByRole('heading', { name: '沖縄店舗在庫管理（DEMO版）' })).toBeVisible()
    const anonymous = await window.evaluate(async () => globalThis.window.storeApp.users.list())
    expect(anonymous).toMatchObject({ ok: false, error: { code: 'AUTH_REQUIRED' } })
    const anonymousStock = await window.evaluate(async () => globalThis.window.storeApp.stock.listActors())
    expect(anonymousStock).toMatchObject({ ok: false, error: { code: 'AUTH_REQUIRED' } })
    await window.getByLabel('ログインID').fill('admin')
    await window.getByLabel('パスワード', { exact: true }).fill('abcd')
    await window.getByRole('button', { name: 'ログイン' }).click()
    await expect(window.getByRole('heading', { name: 'ダッシュボード' })).toBeVisible()
    await window.getByRole('button', { name: '自分のパスワードを変更' }).click()
    await window.getByLabel('現在のパスワード').fill('abcd')
    await window.getByLabel('新しいパスワード（4〜128文字）').fill('wxyz')
    await window.getByLabel('確認入力').fill('wxyZ')
    await window.getByRole('button', { name: '変更する' }).click()
    await expect(window.getByRole('alert')).toContainText('入力内容を確認してください')
    await window.getByLabel('現在のパスワード').fill('abcd')
    await window.getByLabel('新しいパスワード（4〜128文字）').fill('wxyz')
    await window.getByLabel('確認入力').fill('wxyz')
    await window.getByRole('button', { name: '変更する' }).click()
    await window.getByLabel('ログインID').fill('admin')
    await window.getByLabel('パスワード', { exact: true }).fill('wxyz')
    await window.getByRole('button', { name: 'ログイン' }).click()
    await expect(window.getByRole('heading', { name: 'ダッシュボード' })).toBeVisible()
    await window.getByRole('button', { name: '商品一覧' }).click()
    await window.getByRole('button', { name: 'ユーザー管理' }).click()
    await window.getByLabel('ログインID', { exact: true }).fill('staff')
    await window.locator('form.inline-form').first().getByLabel('表示名').fill('店舗担当')
    await window.getByRole('button', { name: 'ユーザー作成・コード発行' }).click()
    const message = await window.locator('.notice').innerText()
    const code = message.match(/再設定コード: ([A-Za-z0-9_-]+)/)?.[1]
    expect(code).toBeTruthy()
    const adminSession = await window.evaluate(async () => globalThis.window.storeApp.auth.getSession())
    if (!adminSession.ok || !adminSession.value) throw new Error('ADMIN session is required')
    const lastAdmin = await window.evaluate(async (userId) => globalThis.window.storeApp.users.update({ userId, displayName: '管理責任者', role: 'STAFF' }), adminSession.value.user.id)
    expect(lastAdmin).toMatchObject({ ok: false, error: { code: 'LAST_ADMIN_REQUIRED' } })
    const staffRow = window.locator('.managed-list li').nth(1)
    await staffRow.getByLabel('表示名').fill('店舗担当者')
    await staffRow.getByRole('button', { name: '変更を保存' }).click()
    await window.getByRole('button', { name: 'カテゴリ管理' }).click()
    await window.getByLabel('カテゴリ名').fill('備品')
    await window.getByRole('button', { name: 'カテゴリを追加' }).click()
    await expect(window.locator('.managed-list').getByText('有効')).toBeVisible()
    await window.getByRole('button', { name: '商品一覧' }).click()
    await window.getByRole('button', { name: '商品を登録' }).click()
    await window.getByLabel('SKU', { exact: true }).fill('BOX_01')
    await window.locator('.editor').getByLabel('商品名', { exact: true }).fill('50% bundle')
    await window.locator('.editor').getByLabel('カテゴリ').selectOption({ label: '備品' })
    await window.getByRole('button', { name: '登録', exact: true }).click()
    await expect(window.locator('tbody').getByText('BOX_01')).toBeVisible()
    const listed = await window.evaluate(async () => globalThis.window.storeApp.products.list({ search: '', categoryId: null, status: 'ALL', stockFilter: 'ALL', sortKey: 'name', direction: 'asc', page: 1, pageSize: 50 }))
    if (!listed.ok || !listed.value.items[0]) throw new Error('Created product is required')
    expect(listed.value.items[0].currentStock).toBe(0)
    const unsafeUpdate = await window.evaluate(async (productId) => {
      const invalidInput = { productId, sku: 'BOX_01', name: '50% bundle', categoryId: null, unit: '個', reorderLevel: 0, note: null, currentStock: 999, initialStock: 999 }
      return globalThis.window.storeApp.products.update(invalidInput)
    }, listed.value.items[0].id)
    expect(unsafeUpdate).toMatchObject({ ok: false, error: { code: 'VALIDATION_ERROR' } })
    await window.getByLabel('SKU・商品名検索').fill('%')
    await expect(window.locator('tbody').getByText('BOX_01')).toBeVisible()
    await window.getByLabel('SKU・商品名検索').fill('no-match')
    await expect(window.getByText('条件に一致する商品はありません。')).toBeVisible()
    await window.getByLabel('SKU・商品名検索').fill('')
    await window.locator('tbody tr').getByRole('button', { name: '在庫変更' }).click()
    await window.getByLabel('操作').selectOption('RECEIPT')
    await window.getByLabel('数量').fill('3')
    await window.getByRole('button', { name: '在庫を記録' }).click()
    await expect(window.getByRole('status')).toContainText('差分 3')
    await window.getByRole('button', { name: '商品一覧' }).click()
    await window.locator('tbody tr').getByRole('button', { name: '在庫変更' }).click()
    await window.getByLabel('操作').selectOption('ISSUE')
    await window.getByLabel('数量').fill('4')
    await window.getByRole('button', { name: '在庫を記録' }).click()
    await expect(window.getByRole('alert')).toContainText('在庫が不足しています')
    await window.getByLabel('数量').fill('3')
    await window.getByRole('button', { name: '在庫を記録' }).click()
    await expect(window.getByRole('status')).toContainText('差分 -3')
    await window.getByLabel('操作').selectOption('ADJUSTMENT')
    await window.getByLabel('棚卸実数').fill('0')
    await window.getByRole('button', { name: '在庫を記録' }).click()
    await expect(window.getByRole('status')).toContainText('差分 0')
    await window.getByRole('button', { name: '在庫履歴' }).click()
    await expect(window.locator('tbody tr')).toHaveCount(3)
    await window.getByLabel('商品候補を検索').fill('BOX_01')
    await window.getByRole('button', { name: '候補を読み込む' }).click()
    await window.locator('.history-filters select').first().selectOption({ label: 'BOX_01 — 50% bundle' })
    await window.getByRole('button', { name: '絞り込む' }).click()
    await expect(window.locator('tbody tr')).toHaveCount(3)
    await window.getByLabel('種別').selectOption('ISSUE')
    await expect(window.locator('tbody tr')).toHaveCount(1)
    await window.getByLabel('操作者').selectOption({ label: '管理責任者（admin）' })
    await expect(window.locator('tbody tr')).toHaveCount(1)
    await window.getByRole('button', { name: 'ダッシュボード' }).click()
    await expect(window.getByText('在庫0商品')).toBeVisible()
    await window.getByRole('button', { name: 'カテゴリ管理' }).click()
    window.once('dialog', (dialog) => void dialog.accept())
    await window.locator('.managed-list li').getByRole('button', { name: '無効化' }).click()
    await window.getByRole('button', { name: '商品一覧' }).click()
    await expect(window.getByText('（無効カテゴリ）')).toBeVisible()
    await window.getByRole('button', { name: 'ログアウト' }).click()
    await window.getByRole('button', { name: '再設定コードを使う' }).click()
    await window.getByLabel('ログインID', { exact: true }).fill('staff')
    await window.getByLabel('再設定コード').fill(code!)
    await window.getByRole('button', { name: 'コードを確認' }).click()
    await expect(window.getByRole('heading', { name: '新しいパスワード' })).toBeVisible()
    await window.getByLabel('新しいパスワード（4〜128文字）').fill('staff')
    await window.getByLabel('確認入力').fill('staf!')
    await window.getByRole('button', { name: 'パスワードを設定' }).click()
    await expect(window.getByRole('alert')).toContainText('入力内容を確認してください')
    await window.getByLabel('新しいパスワード（4〜128文字）').fill('staff')
    await window.getByLabel('確認入力').fill('staff')
    await window.getByRole('button', { name: 'パスワードを設定' }).click()
    await window.getByLabel('ログインID', { exact: true }).fill('staff')
    await window.getByLabel('パスワード', { exact: true }).fill('staff')
    await window.getByRole('button', { name: 'ログイン' }).click()
    await expect(window.getByText('店舗担当者（STAFF）')).toBeVisible()
    const denied = await window.evaluate(async () => globalThis.window.storeApp.users.list())
    expect(denied).toMatchObject({ ok: false, error: { code: 'FORBIDDEN' } })
    const productDenied = await window.evaluate(async () => globalThis.window.storeApp.products.create({ sku: 'DENIED', name: '拒否商品', categoryId: null, unit: '個', reorderLevel: 0, note: null, initialStock: 0 }))
    expect(productDenied).toMatchObject({ ok: false, error: { code: 'FORBIDDEN' } })
    const staffProducts = await window.evaluate(async () => globalThis.window.storeApp.products.list({ search: '', categoryId: null, status: 'ALL', stockFilter: 'ALL', sortKey: 'name', direction: 'asc', page: 1, pageSize: 50 }))
    if (!staffProducts.ok || !staffProducts.value.items[0]) throw new Error('STAFF product list is required')
    const staffStock = await window.evaluate(async (productId) => globalThis.window.storeApp.stock.record({ productId, type: 'RECEIPT', quantity: 1, reasonCode: 'OTHER', note: null }), staffProducts.value.items[0].id)
    expect(staffStock).toMatchObject({ ok: true, value: { currentStock: 1 } })
    await window.getByRole('button', { name: 'ログアウト' }).click()
    await window.getByLabel('ログインID').fill('admin')
    await window.getByLabel('パスワード', { exact: true }).fill('wxyz')
    await window.getByRole('button', { name: 'ログイン' }).click()
    await window.getByRole('button', { name: '商品一覧' }).click()
    await window.getByRole('button', { name: '商品を登録' }).click()
    await window.getByLabel('SKU', { exact: true }).fill('OPENING_E2E')
    await window.locator('.editor').getByLabel('商品名', { exact: true }).fill('初期在庫E2E商品')
    await window.getByLabel('初期在庫数').fill('12')
    await window.getByRole('button', { name: '登録', exact: true }).click()
    await expect(window.locator('tbody')).toContainText('OPENING_E2E')
    const openingProduct = await window.evaluate(async () => globalThis.window.storeApp.products.list({ search: 'OPENING_E2E', categoryId: null, status: 'ALL', stockFilter: 'ALL', sortKey: 'name', direction: 'asc', page: 1, pageSize: 50 }))
    if (!openingProduct.ok || !openingProduct.value.items[0]) throw new Error('Product with opening stock is required')
    expect(openingProduct.value.items[0].currentStock).toBe(12)
    const openingMovement = await window.evaluate(async (productId) => globalThis.window.storeApp.stock.list({ productId, startAt: null, endAt: null, type: 'OPENING', actorUserId: null, page: 1, pageSize: 50 }), openingProduct.value.items[0].id)
    expect(openingMovement).toMatchObject({ ok: true, value: { total: 1, items: [{ stockBefore: 0, quantityDelta: 12, stockAfter: 12 }] } })
    await window.getByRole('button', { name: '在庫履歴' }).click()
    await window.locator('.history-filters select').first().selectOption('')
    await window.getByLabel('種別').selectOption('OPENING')
    await window.getByRole('button', { name: '絞り込む' }).click()
    await expect(window.locator('tbody')).toContainText('初期在庫')
  } finally {
    await app.close()
    await rm(userData, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 })
  }
})
